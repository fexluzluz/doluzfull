import { clsx, type ClassValue } from "clsx";
import { twMerge } from "tailwind-merge";

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

// Calcular volume em M³
export function calculateVolumeM3(heightCm: number, widthCm: number, depthCm: number): number {
  return (heightCm * widthCm * depthCm) / 1000000;
}

// Formatar número para moeda BRL
export function formatCurrency(value: number): string {
  return new Intl.NumberFormat('pt-BR', {
    style: 'currency',
    currency: 'BRL',
  }).format(value);
}

// Formatar número decimal
export function formatNumber(value: number, decimals: number = 2): string {
  return new Intl.NumberFormat('pt-BR', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  }).format(value);
}

// Formatar data
export function formatDate(date: string | Date): string {
  return new Intl.DateTimeFormat('pt-BR', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
  }).format(new Date(date));
}

// Formatar data e hora
export function formatDateTime(date: string | Date): string {
  return new Intl.DateTimeFormat('pt-BR', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  }).format(new Date(date));
}

// Traduzir status de envio
export function translateShipmentStatus(status: string): string {
  const translations: Record<string, string> = {
    pending: 'Pendente',
    processing: 'Em Separação',
    shipped: 'Enviado',
    delivered: 'Entregue',
    cancelled: 'Cancelado',
  };
  return translations[status] || status;
}

// Traduzir tipo de movimentação
export function translateMovementType(type: string): string {
  const translations: Record<string, string> = {
    entry: 'Entrada',
    exit: 'Saída',
  };
  return translations[type] || type;
}

// Traduzir role
export function translateRole(role: string): string {
  const translations: Record<string, string> = {
    admin: 'Administrador',
    client: 'Cliente',
    employee: 'Funcionário',
  };
  return translations[role] || role;
}

